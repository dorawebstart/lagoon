// lib.rs — «серце» застосунку. Тут ми збираємо Tauri: реєструємо команди,
// плагіни, а пізніше — модулі window.rs, media.rs, agent.rs тощо.

/// Команда, яку можна викликати з JavaScript: `invoke("greet", { name: "..." })`.
///
/// - `#[tauri::command]` — атрибут-макрос: генерує код, який перетворює
///   JSON від фронтенду на аргументи функції, а результат — назад на JSON.
/// - `name: &str` — позичене (borrowed) посилання на рядок: функція лише читає
///   текст і не забирає його у власність.
/// - `-> String` — повертаємо новий рядок, яким тепер «володіє» той, хто викликав.
#[tauri::command]
fn greet(name: &str) -> String {
    // format! — макрос (знак оклику), схожий на шаблонні рядки `${}` у JS
    format!("Привіт, {name}! Це відповідь від Rust 🦀")
}

/// Точка запуску застосунку. `pub` означає, що функцію видно поза цим файлом:
/// її викликає main.rs.
#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    // Builder — шаблон «будівельник»: ланцюжком методів налаштовуємо застосунок
    tauri::Builder::default()
        // Список команд, доступних з JS
        .invoke_handler(tauri::generate_handler![greet])
        // generate_context! читає tauri.conf.json під час компіляції
        .run(tauri::generate_context!())
        // run повертає Result; expect зупинить програму з повідомленням, якщо сталася помилка
        .expect("не вдалося запустити застосунок Tauri");
}
